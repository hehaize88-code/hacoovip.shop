import fs from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
const read=file=>fs.readFileSync('worker/'+file,'utf8');
fs.mkdirSync('dist/public/api',{recursive:true});
const index=gunzipSync(fs.readFileSync('worker/assets/search-index.json.gz'));
const data=JSON.parse(index);
const version=createHash('sha256').update(index).digest('hex').slice(0,12);
const client='const INDEX_VERSION='+JSON.stringify(version)+';const LOCALE='+read('localization.json')+';\n'+read('client.js');
const page=read('page.html').replace('{{EXTRA_CSS}}',()=>read('extra.css')).replace('{{CLIENT}}',()=>client.replaceAll('</script','<\\/script'));
fs.writeFileSync('dist/worker.js','const PAGE='+JSON.stringify(page)+'; const INDEX_REPORT='+JSON.stringify(data.report)+';\n'+read('server.mjs'));
fs.writeFileSync('dist/public/api/search-index',index);
fs.copyFileSync('worker/assets/logo.png','dist/public/logo.png');
fs.writeFileSync('dist/public/robots.txt','User-agent: *\nAllow: /\nDisallow: /api/\nSitemap: https://vigorbuybrowse.com/sitemap.xml\n');
const missing=new Set(data.report.unavailableSourceIds);
const paths=['/','/spreadsheet/','/categories/','/image-search/','/guides/','/faq/',...data.products.filter(p=>!missing.has(p[0])).map(p=>'/product/'+p[0])];
fs.writeFileSync('dist/public/sitemap.xml','<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'+[...new Set(paths)].map(p=>'<url><loc>https://vigorbuybrowse.com'+p+'</loc></url>').join('')+'</urlset>');

import {attachEditorial} from '../shopping-editorial/build.mjs';
attachEditorial('dist/worker.js');
